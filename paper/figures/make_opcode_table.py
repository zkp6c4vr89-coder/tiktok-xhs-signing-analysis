#!/usr/bin/env python3
"""Emit the full 365-opcode table as a packed LaTeX longtable fragment.

Reads data/tiktok_opcodes_1.16.6.json and writes paper/opcode_table.tex, packing
4 opcodes per physical row (op, category abbrev, operand-read string) to keep the
reference appendix compact. Regenerable; no hand-typed rows.
Run: python3 paper/figures/make_opcode_table.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
with open(os.path.join(ROOT, "data", "tiktok_opcodes_1.16.6.json")) as f:
    table = json.load(f)

ABBR = {"construct": "con", "bitwise": "bit", "make-function": "mkf", "call": "cal",
        "array": "arr", "store": "sto", "compare": "cmp", "arith": "ari", "load": "lod",
        "other": "oth", "control/exception": "ctl"}

def cell(r):
    reads = r["reads"] if r["reads"] else "--"
    return "%d & %s & %s" % (r["op"], ABBR.get(r["category"], r["category"][:3]), reads)

PER = 4
lines = []
lines.append("% AUTO-GENERATED by paper/figures/make_opcode_table.py -- do not edit by hand.")
lines.append("\\begin{center}\\footnotesize")
colspec = "|".join(["rll"] * PER)
lines.append("\\begin{longtable}{%s}" % colspec)
head = " & ".join(["op & cat & rd"] * PER) + " \\\\ \\hline"
lines.append(head)
lines.append("\\endhead")
for i in range(0, len(table), PER):
    row = table[i:i + PER]
    cells = [cell(r) for r in row]
    while len(cells) < PER:
        cells.append(" & & ")
    lines.append(" & ".join(cells) + " \\\\")
lines.append("\\end{longtable}")
lines.append("\\end{center}")

out = os.path.join(ROOT, "paper", "opcode_table.tex")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, "with", len(table), "opcodes; cat abbrevs:", ABBR)
